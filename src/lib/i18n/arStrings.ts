export function trString(locale: string, en: string, vars?: Record<string, string | number>): string {
  let s = locale === 'ar' ? (AR_STRINGS[en] ?? en) : en;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
